export function getCitationsForSlide(slideId: number, citationIds?: string[]): ReferenceItem[] {
  if (citationIds && citationIds.length > 0) {
    return citationIds.map((id) => REFERENCE_MAP[id]).filter(Boolean);
  }
  return REFERENCES.filter((ref) => ref.slides.includes(slideId));
}
